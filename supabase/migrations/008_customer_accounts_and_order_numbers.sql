-- Customer accounts and short, sequential order numbers for the customer app.
ALTER TABLE public.orders
  ADD COLUMN IF NOT EXISTS order_number BIGINT GENERATED BY DEFAULT AS IDENTITY,
  ADD COLUMN IF NOT EXISTS customer_id UUID REFERENCES auth.users(id) ON DELETE SET NULL;

CREATE UNIQUE INDEX IF NOT EXISTS orders_order_number_uidx ON public.orders(order_number);
CREATE INDEX IF NOT EXISTS orders_customer_created_idx ON public.orders(customer_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.customer_profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name TEXT NOT NULL DEFAULT 'عميل برجر هاوس',
  phone TEXT UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE public.customer_profiles ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS customer_profiles_read_own ON public.customer_profiles;
CREATE POLICY customer_profiles_read_own ON public.customer_profiles
  FOR SELECT TO authenticated USING (id = auth.uid());
DROP POLICY IF EXISTS customer_profiles_update_own ON public.customer_profiles;
CREATE POLICY customer_profiles_update_own ON public.customer_profiles
  FOR UPDATE TO authenticated USING (id = auth.uid()) WITH CHECK (id = auth.uid());

CREATE OR REPLACE FUNCTION public.sync_customer_profile_from_auth()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF NEW.phone IS NOT NULL THEN
    INSERT INTO public.customer_profiles(id, full_name, phone)
    VALUES (NEW.id, COALESCE(NULLIF(NEW.raw_user_meta_data->>'full_name',''), 'عميل برجر هاوس'), NEW.phone)
    ON CONFLICT (id) DO UPDATE SET
      full_name = EXCLUDED.full_name,
      phone = EXCLUDED.phone,
      updated_at = now();
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS on_auth_user_customer_profile ON auth.users;
CREATE TRIGGER on_auth_user_customer_profile
AFTER INSERT OR UPDATE OF phone, raw_user_meta_data ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.sync_customer_profile_from_auth();

ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS customer_read_own_orders ON public.orders;
CREATE POLICY customer_read_own_orders ON public.orders
  FOR SELECT TO authenticated USING (customer_id = auth.uid());
